/** 교회력 절기 이름 */
export function seasonFor(date: string): string {
  const year = parseISO(date).getUTCFullYear()
  const e = easter(year)
  const christmas = `${year}-12-25`
  const advent1 = addDays(weekday(christmas) === 0 ? addDays(christmas, -7) : addDays(christmas, -weekday(christmas)), -21)
  const md = date.slice(5)
  if (md >= '12-25' || md <= '01-05') return '성탄절기'
  if (date >= advent1) return '대림절'
  if (date >= addDays(e, -46) && date < addDays(e, -7)) return '사순절'
  if (date >= addDays(e, -7) && date < e) return '고난주간'
  if (date >= e && date < addDays(e, 49)) return '부활절기'
  if (date >= addDays(e, 49)) return '성령강림 후 절기'
  return '주현절 후 절기'
}

export function readingFor(date: string): Reading {
  const special = specialFor(date)
  const month = Number(date.slice(5, 7))
  const day = Number(date.slice(8, 10))
  const ref = parseRef(special?.passage ?? MONTHLY[month - 1][day - 1])
  return { date, ref, reference: formatRef(ref), occasion: special?.name, season: seasonFor(date) }
}

